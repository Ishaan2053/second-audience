"""`sa propose`: turn the last experiment's failing sessions into a draft of the next one.

Code builds the evidence from the ledger, including whether each agent followed the
`corrected_call` it was offered. A model reads that evidence and proposes one new error style
with a written rationale. Code then checks the proposal: the style must be expressible with
the existing `ErrorStyle` settings and render differently from every arm already tested,
cited sessions must be in the evidence, prose may only use the computed figures, and the slug
must be new. The output is two files for a human to review. Nothing is created in Flagsmith.
"""

import json
import re
from collections import Counter
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict, ValidationError

from second_audience.booking.errors import CAUTION_NOTE
from second_audience.core.ledger import SessionRecord, ToolCallRecord
from second_audience.core.styles import ErrorStyle
from second_audience.operator.analysis import (
    CORRECT,
    OUTCOMES,
    event_value,
    in_experiment,
    scored,
)
from second_audience.operator.gemini import JsonModel
from second_audience.operator.narrative import unsupported_numbers
from second_audience.operator.spec import CONTROL_KEY, Arm, ExperimentSpec, Metric

DRAFT_HEADER = "Draft generated by a model. Review and edit before committing."

SETTING_MEANINGS: dict[str, str] = {
    "suggest_alternative": (
        "adds a `suggestion` object to the error: one alternative slot (room, date, start, "
        "end, reason) from a fixed heuristic that sees only the failed call, never the "
        "user's request, so on trap scenarios the suggestion breaks the request"
    ),
    "corrected_call": (
        "adds a `corrected_call` object: the failed call with the suggestion applied, ready "
        "to send; it is only valid together with suggest_alternative"
    ),
    "caution_note": (
        f"adds a `note` with the fixed text {CAUTION_NOTE!r}; it is only valid together with "
        "suggest_alternative and only appears when a suggestion is present"
    ),
}
"""What each `ErrorStyle` setting adds to a styled error (`booking/errors.py`)."""

_SESSION_ID = re.compile(r"\b[0-9a-f]{32}\b")
"""Session IDs are `uuid4().hex` (`booking/sessions.py`)."""

INSTRUCTIONS = (
    "You are an experimenter improving the error messages an MCP room-booking server returns "
    "to AI agents. A finished A/B experiment compared error styles; you get its arms, the "
    "outcome counts by arm and scenario kind, how often agents followed the corrected call "
    "they were offered, and compact transcripts of sessions that did not end correct. "
    "Propose exactly one new error style to test next against the best-known arm. The style "
    "can only combine the existing settings listed under 'settings'; list in "
    "'variant_settings' the settings that are true, every other setting is false. It must "
    "differ from every arm already tested. Pick 'primary_metric' from 'metrics'. Write "
    "'observed_pattern' (what the evidence shows), 'hypothesis' (one sentence: the change "
    "and its expected effect on the primary metric you chose, with the direction) and "
    "'rationale' (why this style, which risks the guardrails watch). Cite the session IDs "
    "your reasoning relies on in 'cited_sessions' and only use IDs from 'sessions'. Use only "
    "numbers that appear in the evidence; copy them exactly. 'slug' is a new lowercase "
    "experiment name with hyphens, not one listed in 'taken_slugs'. 'variant_key' is a short "
    "snake_case name for the new arm. Plain sentences, no Markdown."
)


class Proposal(BaseModel):
    """What the model must answer, as JSON."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    slug: str
    variant_key: str
    variant_settings: list[str]
    primary_metric: str
    observed_pattern: str
    hypothesis: str
    rationale: str
    cited_sessions: list[str]


class ProposalRejectedError(ValueError):
    """The model's answer failed validation; the message lists every reason."""


# --- evidence --------------------------------------------------------------------------------


def followed_suggestions(calls: list[ToolCallRecord]) -> dict[int, bool]:
    """For each call whose error offered a `corrected_call`: did the next call send exactly it.

    Keyed by the erroring call's `seq`. The session ID argument is ignored; a missing next
    call counts as not followed.
    """
    followed = {}
    for index, call in enumerate(calls):
        offered = call.result.get("corrected_call") if isinstance(call.result, dict) else None
        if not isinstance(offered, dict):
            continue
        after = calls[index + 1] if index + 1 < len(calls) else None
        followed[call.seq] = after is not None and (
            after.tool == offered.get("tool")
            and _without_session(after.arguments) == _without_session(offered.get("arguments"))
        )
    return followed


def _without_session(arguments: Any) -> dict[str, Any]:
    """Call arguments without the session ID, which says nothing about the agent's choice."""
    if not isinstance(arguments, Mapping):
        return {}
    return {key: value for key, value in arguments.items() if key != "session_id"}


def _finished(records: Iterable[SessionRecord]) -> list[SessionRecord]:
    """Exposed, enrolled sessions that have an outcome."""
    return [r for r in records if in_experiment(r) and r.outcome is not None]


def best_known_arm(spec: ExperimentSpec, records: list[SessionRecord]) -> tuple[Arm, str]:
    """The arm with the best ledger mean on the primary metric, and why; control on a tie."""
    metric = spec.primary_metric
    means: dict[str, float] = {}
    for arm in spec.arms:
        mine = [r for r in records if scored(r) and r.variant == arm.key]
        values = [event_value(r, metric.event) for r in mine]
        if values:
            means[arm.key] = sum(values) / len(values)
    if not means:
        return spec.control, f"no scored sessions yet, so {CONTROL_KEY} is kept"
    pick = min if metric.direction == "down" else max
    best = pick(means.values())
    winners = [arm for arm in spec.arms if means.get(arm.key) == best]
    chosen = spec.control if spec.control in winners else winners[0]
    listed = ", ".join(f"{key} {value:.2f}" for key, value in means.items())
    better = "lowest" if metric.direction == "down" else "highest"
    return chosen, (
        f"{better} ledger mean of {metric.name!r} among scored sessions ({listed}); not the "
        "source experiment's decision, which `sa report` makes"
    )


@dataclass(frozen=True)
class Evidence:
    """The evidence pack: what the model sees, and the facts the files are built from."""

    spec: ExperimentSpec
    control: Arm
    control_reason: str
    outcome_rows: list[dict[str, Any]]
    suggestion_rows: list[dict[str, Any]]
    sessions: list[dict[str, Any]]
    taken_slugs: list[str]

    @property
    def session_ids(self) -> set[str]:
        """IDs of the sessions in the pack, the only ones a proposal may cite."""
        return {s["session_id"] for s in self.sessions}

    def figures(self) -> dict[str, Any]:
        """The computed numbers the model's prose may quote, and nothing else."""
        return {
            "outcomes_by_arm_and_kind": self.outcome_rows,
            "corrected_calls_followed": self.suggestion_rows,
            "best_known_arm": self.control_reason,
            "tool_calls_per_session": [s["tool_calls"] for s in self.sessions],
        }

    def identifiers(self) -> list[str]:
        """Names that contain digits but are not figures: slugs, arm keys and scenario IDs."""
        names = {self.spec.slug, *self.taken_slugs, *(arm.key for arm in self.spec.arms)}
        names |= {s["scenario_id"] for s in self.sessions}
        return sorted(names, key=len, reverse=True)

    def pack(self) -> dict[str, Any]:
        """The JSON the model gets."""
        spec = self.spec
        return {
            "source_experiment": spec.slug,
            "source_hypothesis": spec.hypothesis,
            "arms_tested": {arm.key: arm.style.model_dump() for arm in spec.arms},
            "best_known_arm": {"key": self.control.key, "why": self.control_reason},
            "settings": SETTING_MEANINGS,
            "metrics": [
                {"name": m.name, "event": m.event, "direction": m.direction, "role": m.role}
                for m in spec.metrics
            ],
            "outcomes_by_arm_and_kind": self.outcome_rows,
            "corrected_calls_followed": self.suggestion_rows,
            "sessions": self.sessions,
            "taken_slugs": self.taken_slugs,
        }


def _compact(record: SessionRecord, calls: list[ToolCallRecord]) -> dict[str, Any]:
    """One sampled session: assignment, outcome and the transcript without payloads."""
    followed = followed_suggestions(calls)
    return {
        "session_id": record.session_id,
        "arm": record.variant,
        "scenario_id": record.scenario_id,
        "scenario_kind": record.scenario_kind,
        "model": record.agent_label,
        "outcome": record.outcome,
        "final_state": record.final_state,
        "tool_calls": record.tool_call_count,
        "transcript": [
            {
                "seq": call.seq,
                "tool": call.tool,
                "arguments": _without_session(call.arguments),
                "error_code": call.error_code,
                "followed_corrected_call": followed.get(call.seq),
            }
            for call in calls
        ],
    }


def sample_failures(records: list[SessionRecord], limit: int) -> list[SessionRecord]:
    """Up to `limit` non-correct sessions, round-robin over arm and scenario kind, newest first."""
    groups: dict[tuple[str, str], list[SessionRecord]] = {}
    failing = [r for r in _finished(records) if r.outcome != CORRECT]
    for record in sorted(failing, key=lambda r: (r.finished_at, r.session_id), reverse=True):
        groups.setdefault((str(record.variant), record.scenario_kind), []).append(record)
    queues = [groups[key] for key in sorted(groups)]
    picked: list[SessionRecord] = []
    while len(picked) < limit and any(queues):
        for queue in queues:
            if queue and len(picked) < limit:
                picked.append(queue.pop(0))
    return picked


def build_evidence(
    spec: ExperimentSpec,
    records: list[SessionRecord],
    transcripts: Mapping[str, list[ToolCallRecord]],
    limit: int,
    taken_slugs: Iterable[str],
) -> Evidence:
    """Counts by arm and scenario kind, suggestion uptake, and sampled failing transcripts."""
    finished = _finished(records)
    keys = sorted({(str(r.variant), r.scenario_kind) for r in finished})
    outcome_rows, suggestion_rows = [], []
    for arm, kind in keys:
        mine = [r for r in finished if (str(r.variant), r.scenario_kind) == (arm, kind)]
        counts = Counter(r.outcome for r in mine)
        done = [r for r in mine if scored(r)]
        outcome_rows.append(
            {
                "arm": arm,
                "scenario_kind": kind,
                "sessions": len(mine),
                **{name: counts.get(name, 0) for name in OUTCOMES},
                "mean_tool_calls": (
                    f"{sum(r.tool_call_count for r in done) / len(done):.2f}" if done else None
                ),
            }
        )
        offers = [
            followed
            for r in mine
            for followed in followed_suggestions(list(transcripts.get(r.session_id, []))).values()
        ]
        if offers:
            suggestion_rows.append(
                {
                    "arm": arm,
                    "scenario_kind": kind,
                    "corrected_calls_offered": len(offers),
                    "followed": sum(offers),
                }
            )
    control, reason = best_known_arm(spec, finished)
    sampled = sample_failures(finished, limit)
    return Evidence(
        spec=spec,
        control=control,
        control_reason=reason,
        outcome_rows=outcome_rows,
        suggestion_rows=suggestion_rows,
        sessions=[_compact(r, list(transcripts.get(r.session_id, []))) for r in sampled],
        taken_slugs=sorted(set(taken_slugs)),
    )


def taken_slugs(experiments: Path) -> list[str]:
    """Slugs already used by specs, proposals or started experiments under `experiments/`."""
    found = {path.stem for path in experiments.glob("*.yaml")}
    found |= {path.stem for path in (experiments / "proposals").glob("*.yaml")}
    found |= {path.stem for path in (experiments / ".state").glob("*.json")}
    return sorted(found)


# --- validation ------------------------------------------------------------------------------


@dataclass(frozen=True)
class Draft:
    """A validated proposal and the spec built from it."""

    proposal: Proposal
    spec: ExperimentSpec


_NEEDS_SUGGESTION = ("corrected_call", "caution_note")
"""Settings `render_error` applies only after a suggestion is built (`booking/errors.py`)."""


def rendered_behaviour(style: ErrorStyle) -> tuple[bool, ...]:
    """What a style actually adds to a styled error; equal tuples render identically."""
    if not style.suggest_alternative:
        return (False,) * len(ErrorStyle.model_fields)
    return tuple(getattr(style, name) for name in ErrorStyle.model_fields)


def _variant_style(settings: list[str]) -> tuple[dict[str, bool] | None, list[str]]:
    """The variant's flag value from the settings named true, or the reasons it is not valid."""
    known = list(ErrorStyle.model_fields)
    unknown = sorted(set(settings) - set(known))
    if unknown:
        return None, [f"unknown error style settings {unknown}; the only settings are {known}"]
    if "suggest_alternative" not in settings:
        dependent = [name for name in _NEEDS_SUGGESTION if name in settings]
        if dependent:
            return None, [f"{dependent} take effect only together with suggest_alternative"]
    return {name: name in settings for name in known}, []


def build_spec(evidence: Evidence, proposal: Proposal, value: dict[str, bool]) -> ExperimentSpec:
    """The draft spec: best-known arm as control, 50/50, the source's stopping rule."""
    source = evidence.spec
    metrics: list[Metric] = []
    for metric in source.metrics:
        if metric.name == proposal.primary_metric:
            metrics.append(metric.model_copy(update={"role": "primary"}))
        elif metric.role == "primary":
            metrics.append(metric.model_copy(update={"role": "secondary"}))
        else:
            metrics.append(metric)
    return ExperimentSpec.model_validate(
        {
            "slug": proposal.slug,
            "environment": "production",
            "flag": source.flag,
            "hypothesis": proposal.hypothesis,
            "control": {"key": CONTROL_KEY, "value": evidence.control.style.model_dump()},
            "variants": [{"key": proposal.variant_key, "value": value}],
            "metrics": [m.model_dump() for m in metrics],
            "allocation": {
                "traffic_percent": source.allocation.traffic_percent,
                "split": {CONTROL_KEY: 50, proposal.variant_key: 50},
            },
            "stopping_rule": source.stopping_rule.model_dump(),
        }
    )


def validate(raw: str, evidence: Evidence) -> Draft:
    """Check the model's answer against the evidence; raises `ProposalRejectedError`."""
    try:
        proposal = Proposal.model_validate_json(raw)
    except ValidationError as error:
        raise ProposalRejectedError(f"the answer does not match the schema: {error}") from error
    problems: list[str] = []
    if proposal.slug in evidence.taken_slugs:
        problems.append(f"slug {proposal.slug!r} is already taken")
    arm_keys = [arm.key for arm in evidence.spec.arms]
    if proposal.variant_key in {CONTROL_KEY, *arm_keys}:
        problems.append(
            f"variant_key must not be {CONTROL_KEY!r} or an arm key of "
            f"{evidence.spec.slug} {arm_keys}, so the ledger keeps the arms apart"
        )
    value, style_problems = _variant_style(proposal.variant_settings)
    problems += style_problems
    if value is not None:
        behaviour = rendered_behaviour(ErrorStyle.model_validate(value))
        tested = [a.key for a in evidence.spec.arms if rendered_behaviour(a.style) == behaviour]
        if tested:
            problems.append(f"the variant renders the same as arm {tested[0]!r}, already tested")
    metric_names = [m.name for m in evidence.spec.metrics]
    if proposal.primary_metric not in metric_names:
        problems.append(f"primary_metric must be one of {metric_names}")
    prose = " ".join((proposal.observed_pattern, proposal.hypothesis, proposal.rationale))
    cited = set(proposal.cited_sessions) | set(_SESSION_ID.findall(prose))
    if not proposal.cited_sessions:
        problems.append("cite at least one session ID from 'sessions'")
    unknown = sorted(cited - evidence.session_ids)
    if unknown:
        problems.append(f"cited sessions not in the evidence: {unknown}")
    bad_numbers = unsupported_numbers(_without_identifiers(prose, evidence), evidence.figures())
    if bad_numbers:
        problems.append(f"numbers not in the evidence: {bad_numbers}")
    if problems or value is None:
        raise ProposalRejectedError("; ".join(problems))
    try:
        spec = build_spec(evidence, proposal, value)
    except ValidationError as error:
        raise ProposalRejectedError(f"the spec built from it is invalid: {error}") from error
    return Draft(proposal, spec)


def _without_identifiers(prose: str, evidence: Evidence) -> str:
    """The prose without session IDs and other names, so their digits are not read as numbers."""
    prose = _SESSION_ID.sub(" ", prose)
    for name in evidence.identifiers():
        prose = prose.replace(name, " ")
    return prose


@dataclass(frozen=True)
class Attempt:
    """One model answer and why it was rejected, if it was."""

    raw: str
    error: str | None


def draft(model: JsonModel, evidence: Evidence) -> tuple[Draft | None, list[Attempt]]:
    """Ask the model, validate, and retry once with the reasons. `None` if both fail."""
    prompt = json.dumps(evidence.pack(), indent=2)
    attempts: list[Attempt] = []
    for _ in range(2):
        if attempts:
            prompt += (
                f"\n\nYour previous answer was rejected: {attempts[-1].error}\n"
                f"Previous answer: {attempts[-1].raw}\nAnswer again, fixing every problem."
            )
        raw = model(prompt)
        try:
            result = validate(raw, evidence)
        except ProposalRejectedError as error:
            attempts.append(Attempt(raw, str(error)))
            continue
        attempts.append(Attempt(raw, None))
        return result, attempts
    return None, attempts


# --- output ----------------------------------------------------------------------------------


def spec_yaml(spec: ExperimentSpec, source: str) -> str:
    """The spec file, headed by the draft warning."""
    body = yaml.safe_dump(spec.model_dump(mode="json"), sort_keys=False, width=100)
    return f"# {DRAFT_HEADER}\n# Proposed by `sa propose` from experiment {source}.\n{body}"


def _cell(value: object) -> str:
    """One table cell: n/a when missing; pipes and line breaks escaped (field data is untrusted)."""
    if value is None:
        return "n/a"
    text = str(value).replace("\\", "\\\\").replace("|", "\\|")
    return " ".join(text.split())


def _table(header: list[str], rows: Iterable[Iterable[object]]) -> list[str]:
    """A Markdown table; missing values as n/a."""
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows]
    return lines


def rationale_markdown(
    evidence: Evidence, result: Draft, spec_file: str, model: str, now: datetime
) -> str:
    """The rationale file: header, evidence tables from code, then the model's reasoning."""
    proposal, spec, source = result.proposal, result.spec, evidence.spec
    variant = spec.variants[0]
    lines = [
        f"# Proposal: {spec.slug}",
        "",
        f"> **{DRAFT_HEADER}**",
        "",
        f"- Source experiment: `{source.slug}`. Generated {now.isoformat(timespec='seconds')} "
        f"by `sa propose` with `{model}`.",
        f"- Spec: `{spec_file}`.",
        f"- Control: `{evidence.control.flag_value}`, the `{evidence.control.key}` arm of "
        f"`{source.slug}`, as the best-known arm. Why: {evidence.control_reason}.",
        f"- Variant `{variant.key}`: `{variant.flag_value}`.",
        f"- Primary metric: {spec.primary_metric.name}. Split 50/50; stopping rule copied "
        f"from `{source.slug}`.",
        "",
        "## Evidence (computed from the ledger)",
        "",
        f"Exposed, enrolled, finished sessions of `{source.slug}` by arm and scenario kind.",
        "",
    ]
    lines += _table(
        ["Arm", "Scenario kind", "Sessions", *OUTCOMES, "Mean tool calls (scored)"],
        ([row[key] for key in ("arm", "scenario_kind", "sessions", *OUTCOMES, "mean_tool_calls")]
         for row in evidence.outcome_rows),
    )  # fmt: skip
    lines += [
        "",
        "Corrected calls offered in styled errors, and how many the agent sent unchanged as "
        "its next call.",
        "",
    ]
    lines += (
        _table(
            ["Arm", "Scenario kind", "Offered", "Followed"],
            (
                [r["arm"], r["scenario_kind"], r["corrected_calls_offered"], r["followed"]]
                for r in evidence.suggestion_rows
            ),
        )
        if evidence.suggestion_rows
        else ["No corrected calls were offered."]
    )
    lines += [
        "",
        "## Observed pattern (model)",
        "",
        proposal.observed_pattern,
        "",
        "## Hypothesis (model)",
        "",
        proposal.hypothesis,
        "",
        "## Rationale (model)",
        "",
        proposal.rationale,
        "",
        "## Cited sessions (from the ledger)",
        "",
    ]
    by_id = {s["session_id"]: s for s in evidence.sessions}
    lines += _table(
        ["Session", "Arm", "Scenario", "Kind", "Model", "Outcome", "Tool calls",
         "Followed corrected call"],
        (
            [f"`{sid}`", s["arm"], s["scenario_id"], s["scenario_kind"], s["model"],
             s["outcome"], s["tool_calls"], _followed_summary(s["transcript"])]
            for sid in proposal.cited_sessions
            for s in [by_id[sid]]
        ),
    )  # fmt: skip
    lines += [
        "",
        "## Next step",
        "",
        f"Review and edit the spec and this file. Move the spec to `experiments/{spec.slug}.yaml` "
        f"(where `sa status` and `sa report` look for it), add a `{spec.slug}` entry to "
        f"`HYPOTHESIS.md`, commit both, then run `sa start experiments/{spec.slug}.yaml` "
        "(`--dry-run` first). Only one experiment may run on the flag at a time.",
        "",
    ]
    return "\n".join(lines)


def _followed_summary(transcript: list[dict[str, Any]]) -> str:
    """`yes`, `no` or `not offered`, one per offer, in order."""
    marks = [
        "yes" if step["followed_corrected_call"] else "no"
        for step in transcript
        if step["followed_corrected_call"] is not None
    ]
    return ", ".join(marks) if marks else "not offered"
